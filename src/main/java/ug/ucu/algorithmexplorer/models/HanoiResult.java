package ug.ucu.algorithmexplorer.models;

import java.util.List;

/**
 * Stores a complete Tower of Hanoi solution and its measurements.
 *
 * @param diskCount number of disks in the puzzle
 * @param sourcePeg starting peg
 * @param auxiliaryPeg temporary peg
 * @param destinationPeg target peg
 * @param moves generated moves in execution order
 * @param recursiveCallCount total recursive calls
 * @param executionTimeNanos execution time in nanoseconds
 */
public record HanoiResult(
        int diskCount,
        char sourcePeg,
        char auxiliaryPeg,
        char destinationPeg,
        List<HanoiMove> moves,
        long recursiveCallCount,
        long executionTimeNanos
) {

    public HanoiResult {
        if (diskCount < 1) {
            throw new IllegalArgumentException(
                    "Disk count must be at least 1."
            );
        }

        if (moves == null) {
            throw new IllegalArgumentException(
                    "Move list cannot be null."
            );
        }

        if (recursiveCallCount < 0) {
            throw new IllegalArgumentException(
                    "Recursive-call count cannot be negative."
            );
        }

        if (executionTimeNanos < 0) {
            throw new IllegalArgumentException(
                    "Execution time cannot be negative."
            );
        }

        moves = List.copyOf(moves);
    }

    /**
     * Returns the number of moves generated by the solver.
     *
     * @return generated move count
     */
    public int moveCount() {
        return moves.size();
    }

    /**
     * Calculates the expected minimum number of moves: 2^n - 1.
     *
     * @return expected move count
     */
    public long expectedMoveCount() {
        return (1L << diskCount) - 1;
    }

    /**
     * Checks whether the generated count equals 2^n - 1.
     *
     * @return true when the move count is correct
     */
    public boolean hasExpectedMoveCount() {
        return moveCount() == expectedMoveCount();
    }

    /**
     * Converts execution time to milliseconds.
     *
     * @return execution time in milliseconds
     */
    public double executionTimeMillis() {
        return executionTimeNanos / 1_000_000.0;
    }
}